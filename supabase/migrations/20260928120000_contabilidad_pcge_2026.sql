-- ---------- 4d. Cobro o reembolso en caja ligado a un comprobante ----------
CREATE OR REPLACE FUNCTION public.contabilizar_caja(m public.caja_movimientos)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_disp TEXT := cuenta_config(CASE WHEN m.medio_pago = 'Efectivo' THEN 'CAJA' ELSE 'BANCOS' END);
BEGIN
    IF m.comprobante_id IS NULL OR m.tipo NOT IN ('INGRESO', 'EGRESO') OR coalesce(m.monto, 0) <= 0 THEN RETURN NULL; END IF;
    RETURN crear_asiento((m.fecha AT TIME ZONE 'America/Lima')::DATE,
        CASE WHEN m.tipo = 'INGRESO' THEN 'Cobro ' ELSE 'Reembolso ' END || m.comprobante_id || ' · ' || coalesce(m.medio_pago, ''),
        'COBRO', m.id::TEXT,
        CASE WHEN m.tipo = 'INGRESO' THEN jsonb_build_array(linea_json(v_disp, m.monto, 0), linea_json(cuenta_config('CXC'), 0, m.monto))
             ELSE jsonb_build_array(linea_json(cuenta_config('CXC'), m.monto, 0), linea_json(v_disp, 0, m.monto)) END,
        NULL, NULL, NULL, m.responsable);
END;
$$;

CREATE OR REPLACE FUNCTION public.caja_a_diario()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    PERFORM public.contabilizar_caja(NEW);
    RETURN NULL;
END;
$$;

-- ---------- 5. Asientos manuales del dueño o su contador ----------
CREATE OR REPLACE FUNCTION public.registrar_asiento_manual(p JSONB)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_id BIGINT;
BEGIN
    IF NOT public.tiene_rol('{dueno}') THEN RAISE EXCEPTION 'Sólo el dueño registra asientos manuales' USING ERRCODE = '42501'; END IF;
    IF jsonb_array_length(coalesce(p->'lineas', '[]')) < 2 THEN RAISE EXCEPTION 'Un asiento necesita al menos dos líneas'; END IF;
    IF length(btrim(coalesce(p->>'glosa', ''))) < 3 THEN RAISE EXCEPTION 'Escribe la glosa del asiento'; END IF;
    v_id := crear_asiento(coalesce((p->>'fecha')::DATE, (now() AT TIME ZONE 'America/Lima')::DATE), btrim(p->>'glosa'), 'MANUAL', NULL, p->'lineas',
                          NULLIF(p->>'tipo_comprobante', ''), NULLIF(p->>'serie', ''), NULLIF(p->>'numero', ''), p->>'usuario');
    IF v_id IS NULL THEN RAISE EXCEPTION 'El asiento no tiene importes'; END IF;
    RETURN v_id; -- el cuadre se verifica al confirmar
END;
$$;
REVOKE ALL ON FUNCTION public.registrar_asiento_manual(JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.registrar_asiento_manual(JSONB) TO authenticated;

-- ---------- 6. Contabilizar el historial existente y activar los disparadores ----------
DO $$
DECLARE
    rc public.comprobantes;
    rp public.compras;
    rk public.kardex_movimientos;
    rm public.caja_movimientos;
BEGIN
    FOR rc IN SELECT * FROM public.comprobantes ORDER BY fecha_emision, created_at LOOP PERFORM public.contabilizar_comprobante(rc); END LOOP;
    FOR rp IN SELECT * FROM public.compras ORDER BY fecha LOOP PERFORM public.contabilizar_compra(rp); END LOOP;
    FOR rk IN SELECT * FROM public.kardex_movimientos ORDER BY fecha_emision, id LOOP PERFORM public.contabilizar_kardex(rk); END LOOP;
    FOR rm IN SELECT * FROM public.caja_movimientos ORDER BY id LOOP PERFORM public.contabilizar_caja(rm); END LOOP;
END $$;
-- Verifica ya el cuadre de lo contabilizado (y libera los eventos pendientes antes de modificar tablas)
SET CONSTRAINTS public.asiento_debe_igual_haber IMMEDIATE;
SET CONSTRAINTS public.asiento_debe_igual_haber DEFERRED;

