    cuenta VARCHAR(10) NOT NULL REFERENCES public.plan_cuentas(codigo),
    debe NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (debe >= 0),
    haber NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (haber >= 0),
    glosa TEXT,
    CHECK ((debe > 0) <> (haber > 0)) -- cada línea va al debe o al haber, nunca a ambos
);
