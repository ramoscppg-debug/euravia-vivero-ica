-- ---------- 1. Plan de cuentas ----------
CREATE TABLE IF NOT EXISTS public.plan_cuentas (
    codigo VARCHAR(10) PRIMARY KEY CHECK (codigo ~ '^[0-9]{2,10}$'),
    nombre TEXT NOT NULL,
    elemento SMALLINT NOT NULL CHECK (elemento BETWEEN 1 AND 9),
    padre VARCHAR(10) REFERENCES public.plan_cuentas(codigo),
    nivel SMALLINT GENERATED ALWAYS AS (length(codigo)) STORED,
    naturaleza VARCHAR(9) CHECK (naturaleza IN ('DEUDORA', 'ACREEDORA')),
    acepta_movimiento BOOLEAN NOT NULL DEFAULT TRUE, -- sólo las cuentas de último nivel reciben asientos
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    personalizada BOOLEAN NOT NULL DEFAULT FALSE      -- divisionaria creada por la empresa
);
CREATE INDEX IF NOT EXISTS plan_cuentas_padre_idx ON public.plan_cuentas (padre);

