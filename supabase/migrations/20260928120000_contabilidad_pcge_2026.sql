        jsonb_build_array(linea_json(cuenta_config('IGV'), p.igv, 0), linea_json(cuenta_config('CXP'), 0, p.igv)),
        '01', split_part(p.id, '-', 1), split_part(p.id, '-', 2), NULL);
END;
$$;

