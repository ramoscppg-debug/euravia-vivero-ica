CREATE INDEX IF NOT EXISTS asiento_lineas_asiento_idx ON public.asiento_lineas (asiento_id);

CREATE OR REPLACE FUNCTION public.asiento_linea_imputable()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    PERFORM public.validar_cuenta_imputable(NEW.cuenta);
    RETURN NEW;
END;
$$;
CREATE TRIGGER asiento_linea_cuenta_valida BEFORE INSERT OR UPDATE ON public.asiento_lineas
    FOR EACH ROW EXECUTE FUNCTION public.asiento_linea_imputable();

/** Partida doble: al confirmar la transacción, cada asiento tocado debe cuadrar. */
CREATE OR REPLACE FUNCTION public.asiento_cuadrado()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
    v_id BIGINT := coalesce(NEW.asiento_id, OLD.asiento_id);
    v_debe NUMERIC;
    v_haber NUMERIC;
BEGIN
    SELECT coalesce(sum(debe), 0), coalesce(sum(haber), 0) INTO v_debe, v_haber FROM public.asiento_lineas WHERE asiento_id = v_id;
    IF v_debe <> v_haber THEN
        RAISE EXCEPTION 'Asiento % descuadrado: debe % ≠ haber %', v_id, v_debe, v_haber;
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER asiento_debe_igual_haber AFTER INSERT OR UPDATE OR DELETE ON public.asiento_lineas
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.asiento_cuadrado();

/** Crea un asiento con sus líneas ([{cuenta, debe, haber, glosa}]); omite las líneas en cero. */
CREATE OR REPLACE FUNCTION public.crear_asiento(p_fecha DATE, p_glosa TEXT, p_origen TEXT, p_origen_id TEXT, p_lineas JSONB,
    p_t10 TEXT DEFAULT NULL, p_serie TEXT DEFAULT NULL, p_numero TEXT DEFAULT NULL, p_usuario TEXT DEFAULT NULL)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_id BIGINT;
    l JSONB;
BEGIN
    IF p_origen <> 'MANUAL' AND EXISTS (SELECT 1 FROM public.asientos WHERE origen = p_origen AND origen_id = p_origen_id) THEN
        RETURN NULL; -- ya contabilizado
    END IF;
    IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(p_lineas) x WHERE round(coalesce((x->>'debe')::NUMERIC, 0) + coalesce((x->>'haber')::NUMERIC, 0), 4) > 0) THEN
        RETURN NULL; -- sin importes (p. ej. costo cero)
    END IF;
    INSERT INTO public.asientos (fecha, glosa, origen, origen_id, sunat_tipo_comprobante, comprobante_serie, comprobante_numero, registrado_por)
    VALUES (p_fecha, p_glosa, p_origen, p_origen_id, p_t10, p_serie, p_numero, p_usuario)
    RETURNING id INTO v_id;
    FOR l IN SELECT * FROM jsonb_array_elements(p_lineas) LOOP
        IF round(coalesce((l->>'debe')::NUMERIC, 0), 4) > 0 OR round(coalesce((l->>'haber')::NUMERIC, 0), 4) > 0 THEN
            INSERT INTO public.asiento_lineas (asiento_id, cuenta, debe, haber, glosa)
            VALUES (v_id, l->>'cuenta', round(coalesce((l->>'debe')::NUMERIC, 0), 4), round(coalesce((l->>'haber')::NUMERIC, 0), 4), l->>'glosa');
        END IF;
    END LOOP;
    RETURN v_id;
END;
$$;
REVOKE ALL ON FUNCTION public.crear_asiento(DATE, TEXT, TEXT, TEXT, JSONB, TEXT, TEXT, TEXT, TEXT) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.cuenta_config(p_clave TEXT) RETURNS TEXT
LANGUAGE sql STABLE SET search_path = public AS $$ SELECT cuenta FROM public.config_contable WHERE clave = p_clave $$;

CREATE OR REPLACE FUNCTION public.linea_json(p_cuenta TEXT, p_debe NUMERIC, p_haber NUMERIC, p_glosa TEXT DEFAULT NULL) RETURNS JSONB
LANGUAGE sql IMMUTABLE AS $$ SELECT jsonb_build_object('cuenta', p_cuenta, 'debe', coalesce(p_debe, 0), 'haber', coalesce(p_haber, 0), 'glosa', p_glosa) $$;

-- ---------- 4a. Kardex → asiento (usa el costo promedio que acaba de fijar el Kardex) ----------
CREATE OR REPLACE FUNCTION public.contabilizar_kardex(k public.kardex_movimientos)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_tipo TEXT;
    m public.cuentas_existencia;
    b public.cuentas_existencia;  -- respaldo: mercaderías
    v_monto NUMERIC := round(coalesce(k.costo_total, 0), 4);
    v_nombre TEXT;
    v_lineas JSONB;
    v_glosa TEXT;
BEGIN
    IF v_monto <= 0 THEN RETURN NULL; END IF;
    SELECT tipo_existencia, nombre INTO v_tipo, v_nombre FROM public.productos WHERE sku = k.producto_sku;
    -- Lo que entra por producción propia es producto terminado (PCGE: cuenta 21)
    IF k.sunat_tipo_operacion = '19' AND v_tipo IS DISTINCT FROM '02' THEN
        UPDATE public.productos SET tipo_existencia = '02' WHERE sku = k.producto_sku;
        v_tipo := '02';
    END IF;
    SELECT * INTO m FROM public.cuentas_existencia WHERE tipo_existencia = coalesce(v_tipo, '01');
    SELECT * INTO b FROM public.cuentas_existencia WHERE tipo_existencia = '01';
    IF m.tipo_existencia IS NULL THEN m := b; END IF;

    CASE k.sunat_tipo_operacion
        WHEN '02' THEN -- compra: 60 a 42 (base) y destino 2x a 61
            v_glosa := 'Compra de ' || v_nombre;
            v_lineas := jsonb_build_array(
                linea_json(coalesce(m.compra, b.compra), v_monto, 0), linea_json(cuenta_config('CXP'), 0, v_monto),
                linea_json(m.inventario, v_monto, 0), linea_json(coalesce(m.variacion, b.variacion), 0, v_monto));
        WHEN '01' THEN -- costo de lo vendido
            v_glosa := 'Costo de venta de ' || v_nombre;
            v_lineas := jsonb_build_array(linea_json(m.costo_venta, v_monto, 0), linea_json(m.inventario, 0, v_monto));
        WHEN '05' THEN -- devolución del cliente: vuelve al inventario
            v_glosa := 'Devolución de ' || v_nombre;
            v_lineas := jsonb_build_array(linea_json(m.inventario, v_monto, 0), linea_json(m.costo_venta, 0, v_monto));
        WHEN '10' THEN -- insumo a producción: 61 a 24/25/26
            v_glosa := 'Consumo de ' || v_nombre || ' en producción';
            v_lineas := jsonb_build_array(linea_json(coalesce(m.variacion, b.variacion), v_monto, 0), linea_json(m.inventario, 0, v_monto));
        WHEN '19' THEN -- producción / cosecha propia: 21 a 711
            v_glosa := 'Producción propia de ' || v_nombre;
            v_lineas := jsonb_build_array(linea_json(m.inventario, v_monto, 0), linea_json(coalesce(m.variacion_produccion, '7111'), 0, v_monto));
        WHEN '13', '14' THEN -- merma o desmedro: 695 a inventario
            v_glosa := CASE k.sunat_tipo_operacion WHEN '13' THEN 'Merma de ' ELSE 'Desmedro de ' END || v_nombre;
            v_lineas := jsonb_build_array(linea_json(m.deterioro, v_monto, 0), linea_json(m.inventario, 0, v_monto));
        WHEN '16' THEN
            v_glosa := 'Inventario inicial de ' || v_nombre;
            v_lineas := jsonb_build_array(linea_json(m.inventario, v_monto, 0), linea_json(cuenta_config('APERTURA'), 0, v_monto));
        ELSE -- 28 ajuste y 99 otros (materiales usados en servicios)
            IF k.movimiento = 'ENTRADA' THEN
                v_glosa := 'Sobrante de ' || v_nombre;
                v_lineas := jsonb_build_array(linea_json(m.inventario, v_monto, 0), linea_json(cuenta_config('SOBRANTES'), 0, v_monto));
            ELSIF k.sunat_tipo_operacion = '99' THEN
                v_glosa := 'Materiales de ' || v_nombre || ' usados en servicio';
                v_lineas := jsonb_build_array(linea_json(cuenta_config('COSTO_SERV'), v_monto, 0), linea_json(m.inventario, 0, v_monto));
            ELSE
                v_glosa := 'Faltante de ' || v_nombre;
                v_lineas := jsonb_build_array(linea_json(cuenta_config('FALTANTES'), v_monto, 0), linea_json(m.inventario, 0, v_monto));
            END IF;
    END CASE;

    RETURN crear_asiento(k.fecha_emision, v_glosa || ' (' || coalesce(k.documento_referencia, 'Kardex') || ')', 'KARDEX', k.id::TEXT, v_lineas,
                         k.sunat_tipo_comprobante, k.comprobante_serie, k.comprobante_numero, k.usuario_responsable);
END;
$$;

CREATE OR REPLACE FUNCTION public.kardex_a_diario()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    PERFORM public.contabilizar_kardex(NEW);
    RETURN NULL;
END;
$$;

-- ---------- 4b. Comprobante → venta (o nota de crédito) ----------
CREATE OR REPLACE FUNCTION public.contabilizar_comprobante(c public.comprobantes)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_nc BOOLEAN := c.tipo_comprobante = '07';
    v_total NUMERIC := round(c.monto_total, 4);
    v_igv NUMERIC := round(coalesce(c.total_igv, 0), 4);
    v_lineas JSONB := '[]';
    r RECORD;
    v_base NUMERIC := 0;
    v_ultima TEXT;
BEGIN
    IF v_total <= 0 THEN RETURN NULL; END IF;
    -- Base por cuenta de ingreso (70x por tipo de existencia; servicios y delivery a 7032)
    FOR r IN
        SELECT CASE WHEN p.sku IS NULL THEN cuenta_config(CASE WHEN v_nc THEN 'DEVOL_SERV' ELSE 'VENTA_SERV' END)
                    ELSE (SELECT CASE WHEN v_nc THEN e.devolucion_venta ELSE e.venta END FROM public.cuentas_existencia e WHERE e.tipo_existencia = coalesce(p.tipo_existencia, '01')) END AS cuenta,
               round(sum(coalesce((it->>'subtotal')::NUMERIC, (it->>'total')::NUMERIC / 1.18)), 4) AS base
        FROM jsonb_array_elements(coalesce(c.items, '[]')) it
        LEFT JOIN public.productos p ON p.sku = it->>'sku'
        GROUP BY 1 ORDER BY 2
    LOOP
        v_lineas := v_lineas || CASE WHEN v_nc THEN linea_json(r.cuenta, r.base, 0) ELSE linea_json(r.cuenta, 0, r.base) END;
        v_base := v_base + r.base;
        v_ultima := r.cuenta;
    END LOOP;
    IF v_ultima IS NULL THEN -- sin detalle: todo como venta de mercaderías
        v_ultima := (SELECT CASE WHEN v_nc THEN devolucion_venta ELSE venta END FROM public.cuentas_existencia WHERE tipo_existencia = '01');
        v_base := v_total - v_igv;
        v_lineas := jsonb_build_array(CASE WHEN v_nc THEN linea_json(v_ultima, v_base, 0) ELSE linea_json(v_ultima, 0, v_base) END);
    END IF;
    -- Redondeo: la diferencia de céntimos va a la cuenta de ingreso de mayor base
    IF v_base + v_igv <> v_total THEN
        v_lineas := v_lineas || CASE WHEN v_nc THEN linea_json(v_ultima, GREATEST(v_total - v_igv - v_base, 0), GREATEST(v_base + v_igv - v_total, 0))
                                     ELSE linea_json(v_ultima, GREATEST(v_base + v_igv - v_total, 0), GREATEST(v_total - v_igv - v_base, 0)) END;
    END IF;
    v_lineas := v_lineas || CASE WHEN v_nc THEN jsonb_build_array(linea_json(cuenta_config('IGV'), v_igv, 0), linea_json(cuenta_config('CXC'), 0, v_total))
                                 ELSE jsonb_build_array(linea_json(cuenta_config('CXC'), v_total, 0), linea_json(cuenta_config('IGV'), 0, v_igv)) END;
    RETURN crear_asiento(c.fecha_emision,
        CASE WHEN v_nc THEN 'Nota de crédito ' ELSE 'Venta ' END || c.id || ' · ' || c.cliente,
        'VENTA', c.id, v_lineas,
        CASE c.tipo_comprobante WHEN '01' THEN '01' WHEN '03' THEN '03' WHEN '07' THEN '07' ELSE '00' END,
        c.serie, lpad(c.correlativo::TEXT, 8, '0'), NULL);
END;
$$;

CREATE OR REPLACE FUNCTION public.comprobante_a_diario()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    PERFORM public.contabilizar_comprobante(NEW);
    RETURN NULL;
END;
$$;

-- ---------- 4c. Compra → IGV crédito fiscal (la base la contabiliza el Kardex) ----------
