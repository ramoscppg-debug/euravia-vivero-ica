-- Jerarquía: el padre es el prefijo existente más largo; sólo las hojas aceptan movimiento
UPDATE public.plan_cuentas c
   SET padre = (SELECT p.codigo FROM public.plan_cuentas p
                 WHERE c.codigo LIKE p.codigo || '%' AND p.codigo <> c.codigo
                 ORDER BY length(p.codigo) DESC LIMIT 1);
UPDATE public.plan_cuentas c
   SET acepta_movimiento = NOT EXISTS (SELECT 1 FROM public.plan_cuentas h WHERE h.padre = c.codigo),
       naturaleza = CASE
           WHEN c.codigo ~ '^(19|29|36|39)' THEN 'ACREEDORA' -- cuentas de valuación del activo
           WHEN c.elemento IN (1, 2, 3, 6, 9) THEN 'DEUDORA'
           WHEN c.codigo ~ '^88' THEN 'DEUDORA'
           ELSE 'ACREEDORA' END;

/** Nuevas divisionarias de la empresa: se cuelgan de su prefijo y el padre deja de recibir movimientos. */
CREATE OR REPLACE FUNCTION public.plan_cuentas_jerarquia()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    NEW.elemento := left(NEW.codigo, 1)::SMALLINT;
    SELECT p.codigo INTO NEW.padre FROM public.plan_cuentas p
     WHERE NEW.codigo LIKE p.codigo || '%' AND p.codigo <> NEW.codigo ORDER BY length(p.codigo) DESC LIMIT 1;
    IF NEW.padre IS NULL AND length(NEW.codigo) > 2 THEN RAISE EXCEPTION 'La cuenta % no tiene una cuenta superior en el plan', NEW.codigo; END IF;
    IF NEW.padre IS NOT NULL THEN
        IF EXISTS (SELECT 1 FROM public.asiento_lineas WHERE cuenta = NEW.padre) THEN
            RAISE EXCEPTION 'La cuenta % ya tiene movimientos: no se puede subdividir', NEW.padre;
        END IF;
        NEW.naturaleza := coalesce(NEW.naturaleza, (SELECT naturaleza FROM public.plan_cuentas WHERE codigo = NEW.padre));
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.plan_cuentas_padre_sin_movimiento()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    UPDATE public.plan_cuentas SET acepta_movimiento = FALSE WHERE codigo = NEW.padre;
    RETURN NEW;
END;
$$;

